"""Generate a Mermaid ER diagram from SQLAlchemy model metadata.

Imports all VTV model modules to populate Base.metadata, then walks
sorted_tables to emit deterministic Mermaid erDiagram markup.
Prints to stdout — the Makefile redirects to docs/schema/er.md.
"""

