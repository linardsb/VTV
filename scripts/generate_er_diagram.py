# ---------------------------------------------------------------------------
# Type mapping: SQLAlchemy type class name → short Mermaid label
# ---------------------------------------------------------------------------

_TYPE_MAP: dict[str, str] = {
    "Integer": "int",
    "BigInteger": "int",
    "SmallInteger": "int",
    "String": "string",
    "Text": "string",
    "VARCHAR": "string",
    "Boolean": "bool",
    "DateTime": "datetime",
    "Date": "date",
    "Time": "time",
    "Float": "float",
    "Numeric": "numeric",
    "UUID": "uuid",
    "Uuid": "uuid",
    "JSON": "jsonb",
    "JSONB": "jsonb",
    "LargeBinary": "bytes",
    "Enum": "enum",
    "ARRAY": "array",
}


def _col_type_label(col: Column[Any]) -> str:
    """Return a short Mermaid-friendly type label for a column."""
    type_obj = col.type
    cls_name = type(type_obj).__name__

    # GeoAlchemy2
    if cls_name in ("Geometry", "Geography"):
        return "geometry"
    # pgvector
    if cls_name == "Vector":
        return "vector"

    return _TYPE_MAP.get(cls_name, cls_name.lower())


def _sanitize(name: str) -> str:
    """Replace characters that break Mermaid identifiers."""
    return re.sub(r"[^a-zA-Z0-9_]", "_", name)


def _col_markers(col: Column[Any]) -> str:
    """Return PK/FK markers for a column."""
    parts: list[str] = []
    if col.primary_key:
        parts.append("PK")
    if col.foreign_keys:
        parts.append("FK")
    return " ".join(parts)


def _emit_table(table: Table) -> list[str]:
    """Emit Mermaid lines for one table entity."""
    lines: list[str] = []
    name = _sanitize(table.name)
    lines.append(f"    {name} {{")
    for col in table.columns:
        col_name = _sanitize(col.name)
        col_type = _col_type_label(col)
        markers = _col_markers(col)
        if markers:
            lines.append(f"        {col_type} {col_name} {markers}")
        else:
            lines.append(f"        {col_type} {col_name}")
    lines.append("    }")
    return lines


def _emit_relationships(tables: list[Table]) -> list[str]:
    """Emit Mermaid relationship lines from FK constraints."""
    lines: list[str] = []
    seen: set[tuple[str, str, str]] = set()

    for table in tables:
        for fk_constraint in table.foreign_key_constraints:
            if not isinstance(fk_constraint, ForeignKeyConstraint):
                continue

            # Source table (the one with the FK column)
            src = _sanitize(table.name)

            # Target table (the one being referenced)
            ref_cols = list(fk_constraint.referred_table.columns)
            if not ref_cols:
                continue
            tgt = _sanitize(fk_constraint.referred_table.name)

            # Use the first FK column name as the label
            fk_col_names = [_sanitize(c.name) for c in fk_constraint.columns]
            label = fk_col_names[0] if fk_col_names else ""

            # Dedup
            key = (src, tgt, label)
            if key in seen:
                continue
            seen.add(key)

            # Determine cardinality: nullable FK → zero-or-one, else exactly-one
            nullable = any(col.nullable for col in fk_constraint.columns)
            if nullable:
                # src has optional reference to tgt
                arrow = "}o--||"
            else:
                # src has required reference to tgt
                arrow = "}|--||"

            lines.append(f'    {src} {arrow} {tgt} : "{label}"')

    return lines


def generate() -> str:
    """Generate the full Mermaid ER diagram markdown document."""
    tables = list(Base.metadata.sorted_tables)

    parts: list[str] = [
        "# Database Schema — ER Diagram",
        "",
        "> Auto-generated by `make er-diagram` from SQLAlchemy models.",
        "> Do not edit manually — re-run after migrations.",
        "",
        "```mermaid",
        "erDiagram",
    ]

    # Emit all table entities
    for table in tables:
        parts.extend(_emit_table(table))

    # Emit relationships
    parts.append("")
    parts.extend(_emit_relationships(tables))

    parts.append("```")
    parts.append("")  # trailing newline
    return "\n".join(parts)


if __name__ == "__main__":
    print(generate())
